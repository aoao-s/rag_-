# 只有当"第一名 - 第二名"够大、且第一名绝对分够高时才敢给结论。
# 两个阈值在 **train 2100 条**上扫描确定，test 500 条只跑一次报数（设计文档 §3.7）。
#
# 3.0 / 1.0 是在 train 上十二组 (min_score, min_margin) 里选出的最优点：
# macro-F1 0.9813 / acc 0.9729 / unknown 1.76%。抬到 4.0 / 2.0 会掉到 0.93 附近——
# 规则表的判别力主要在"谁压过谁"，不在"分数够不够高"，margin 抬高只会把
# 权重 3~4 的短问句（`这道题怎么解`）整批推进 unknown。
#
# 为什么 1.0 这个 margin 不与 §7.7 的 0.6 置信度闸门打架：`_result()` 的置信度是
# `0.55 + margin × 0.05` 截到 0.99，margin = 1 恰好给 0.60（正落在闸门上），
# margin = 0 给 0.55 < 0.6 → 落 unknown。两条线在同一个位置收口，不是两套标准。
MIN_SCORE: Final[float] = 3.0
MIN_MARGIN: Final[float] = 1.0


class IntentClassifier:
    """规则版意图分类器。签名与将来的模型版一致，编排层不需要知道用的是哪个。"""

    def __init__(
        self,
        keywords: dict[str, tuple[tuple[str, int], ...]] | None = None,
        *,
        min_score: float = MIN_SCORE,
        min_margin: float = MIN_MARGIN,
    ) -> None:
        self.keywords = keywords or KEYWORDS
        self.min_score = min_score
        self.min_margin = min_margin

    def classify(self, query: str, history: list[str] | None = None) -> IntentResult:
        """分类。`history` 目前不参与打分（规则版用不上），保留参数是为了将来换模型时
        不改调用点——§7.6 的契约里带它。"""
        text = (query or "").strip()
        if not text:
            return _unknown(0.0, "empty_query")

        scores = self._scores(text)
        ranked = sorted(scores.items(), key=lambda kv: kv[1], reverse=True)
        top_label, top_score = ranked[0]
        second = ranked[1][1] if len(ranked) > 1 else 0.0

        if top_score >= self.min_score and (top_score - second) >= self.min_margin:
            return _result(top_label, top_score, second)

        # 没有关键词命中：三张弱信号表依次判断，顺序即效力从强到弱。
        if top_score <= 0:
            if any(h in text for h in CHITCHAT_HINTS):
                return _result("闲聊", 6.0, 0.0)
            # 有学业语义却没有任何关键词覆盖 → 不猜，交全库检索 + 追问
            if any(h in text for h in ACADEMIC_HINTS):
                return _unknown(0.35, "academic_hint_only")
            # 弱"超出范围"信号同样**不拒答**，只落 unknown（理由见信号表注释）
            if any(h in text for h in OUT_OF_DOMAIN_HINTS):
                return _unknown(0.40, "out_of_domain_hint_only")
            # 短句兜底只在**没有疑问形态**时成立："怎么弄""啥意思"这类短问句
            # 一旦被当成寒暄就会跳过检索，所以宁可落 unknown 走全库检索 + 追问。
            if len(text) <= 12 and not looks_like_question(text):
                return _result("闲聊", 5.0, 0.0)
            return _unknown(0.3, "no_signal")

        # 命中了但不够自信（分数低或两家打平）：按 §7.7 不许硬路由
        return _unknown(min(0.59, 0.3 + top_score * 0.05), f"weak_{top_label}")

    def _scores(self, text: str) -> dict[str, float]:
        """按标签累加权重。

        种子集覆盖**全部** `INTENT_LABELS`：闲聊与超出范围现在也是关键词类
        （旧实现里它们只走"零分兜底"，因为闲聊不占检索、没有关键词），
        不从零开始就会在下标访问时 KeyError。
        """
        scores = {label: 0.0 for label in INTENT_LABELS}
        for label, words in self.keywords.items():
            for word, weight in words:
                if word in text:
                    scores[label] = scores.get(label, 0.0) + weight
        return scores


def _result(label: str, top: float, second: float) -> IntentResult:
    """有结论时统一出行：档位由 `profiles` 数据表给，本文件不写任何 if/else 分支。"""
    label = normalize_intent_label(label)
    # 置信度只用于日志与门槛，不参与路由；上限 0.99 免得看起来像"确定无疑"
    confidence = round(min(0.99, 0.55 + (top - second) * 0.05), 2)
    return IntentResult(
        label=label,
        confidence=confidence,
        method="rule",
        profile=profile_for(label).name,
    )


def _unknown(confidence: float, reason: str) -> IntentResult:
    """低置信 → unknown（§7.7 硬规则 2、3）。`reason` 只进日志，不进响应。"""
    log.debug("intent_unknown", reason=reason, confidence=round(confidence, 2))
    return IntentResult(
        label=INTENT_FALLBACK,
        confidence=round(confidence, 2),
        method="fallback",
        profile=profile_for(INTENT_FALLBACK).name,
    )


def classify(query: str, history: list[str] | None = None) -> IntentResult:
    """无状态快捷入口，供脚本与单测使用。"""
    return IntentClassifier().classify(query, history)


